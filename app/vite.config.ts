import { defineConfig } from 'vitest/config';
import type { Plugin } from 'vite';
import basicSsl from '@vitejs/plugin-basic-ssl';

/**
 * Tiny hand-written PWA helper: after the bundle is written, emit `sw.js` with the exact list of
 * hashed app-shell files so the service worker can precache them. No third-party PWA plugin, no CDN.
 */
function serviceWorkerPlugin(): Plugin {
  return {
    name: 'dwell-sw',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const shell = ['./', './index.html', './manifest.webmanifest', './icons/icon.svg', './icons/icon-192.png',
        ...files.map((f) => './' + f)];
      const version = Date.now().toString(36);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: SW_TEMPLATE.replace('__SHELL__', JSON.stringify([...new Set(shell)]))
          .replace('__VERSION__', version),
      });
    },
  };
}

const SW_TEMPLATE = `// Generated by vite.config.ts (dwell-sw). Caches the app shell; reports are network-first.
const CACHE = 'dwell-shell-__VERSION__';
const SHELL = __SHELL__;
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(
    keys.filter((k) => k.startsWith('dwell-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (url.pathname.includes('/reports/')) {
    // network-first so freshly generated reports show up; fall back to the last cached copy offline
    e.respondWith(fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match(req).then((r) => r || Response.error())));
    return;
  }
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./index.html')));
    return;
  }
  e.respondWith(caches.match(req).then((r) => r || fetch(req)));
});
`;

// `--mode lan` (npm run dev:lan): serve over HTTPS with a locally generated self-signed cert, because
// phone browsers only allow camera / compass access on secure origins (localhost is exempt).
export default defineConfig(({ mode }) => ({
  base: './',
  plugins: [serviceWorkerPlugin(), ...(mode === 'lan' ? [basicSsl()] : [])],
  build: { target: 'es2020', chunkSizeWarningLimit: 900 },
  test: { environment: 'node', include: ['test/**/*.test.ts'] },
}));
