import './styles.css';
import { roomCards, stopAudio } from './cards';
import { mountCapture } from './capture';
import { METRICS, summarize } from './compare';
import { fetchIndex, fetchReport, readReportFile, ReportError, type IndexEntry, type LoadedReport, type Report } from './data/schema';
import { clear, h } from './dom';
import { defaultHourIndex, formatHour, sliderToIndex } from './geo';
import { Viewer3D } from './viewer3d';

const STANDING_DISCLAIMER = 'Dwell gives estimates with uncertainty intervals — not a building inspection, and not a mould, structural or legal assessment.';

const app = document.getElementById('app')!;
const banner = h('div', { class: 'disclaimer', role: 'note' }, STANDING_DISCLAIMER);
const nav = h('nav', { class: 'tabs', 'aria-label': 'Sections' },
  ...[['viewer', 'Viewer'], ['compare', 'Compare'], ['capture', 'Capture']].map(([id, label]) =>
    h('a', { href: `#/${id}`, 'data-route': id }, label)));
const main = h('main', { id: 'main' });
app.append(h('header', { class: 'top' }, h('h1', {}, 'Dwell'), nav), banner, main);

// ---- state ---------------------------------------------------------------------------------
let index: IndexEntry[] = [];
let indexError: string | null = null;
const loaded = new Map<string, LoadedReport>(); // key: index id or "file:<name>"
let currentKey: string | null = null;
let cleanup: (() => void) | null = null;

async function getReport(key: string): Promise<LoadedReport> {
  const hit = loaded.get(key);
  if (hit) return hit;
  const lr = await fetchReport(key);
  loaded.set(key, lr);
  return lr;
}

function options(): { key: string; label: string }[] {
  const opts = index.map((e) => ({ key: e.id, label: `${e.label}${e.data_kind === 'synthetic' ? ' — synthetic' : ''}` }));
  for (const [k, lr] of loaded) if (k.startsWith('file:')) opts.push({ key: k, label: `${lr.report.unit.label} (opened file)` });
  return opts;
}

function errorBox(err: unknown): HTMLElement {
  const details = err instanceof ReportError ? err.details : [];
  return h('div', { class: 'panel error', role: 'alert' },
    h('strong', {}, err instanceof Error ? err.message : String(err)),
    details.length ? h('ul', {}, ...details.map((d) => h('li', {}, d))) : null);
}

function emptyState(): HTMLElement {
  return h('div', { class: 'panel empty' },
    h('h2', {}, 'No reports yet'),
    h('p', {}, 'No reports yet — run ', h('code', {}, 'make demo'), ' to generate them, or open a report.json file with the button above.'),
    indexError ? h('p', { class: 'muted' }, indexError) : null);
}

function badge(r: Report): HTMLElement | null {
  return r.data_kind === 'synthetic'
    ? h('span', { class: 'badge synthetic', title: 'This unit is generated by the synthetic world model, not a real apartment.' }, 'SYNTHETIC DEMO UNIT')
    : null;
}

function filePicker(onLoaded: (key: string) => void): HTMLElement {
  const input = h('input', { type: 'file', accept: '.json,application/json', class: 'visually-hidden', id: 'file-in' });
  input.addEventListener('change', async () => {
    const f = input.files?.[0];
    if (!f) return;
    try {
      const lr = await readReportFile(f);
      const key = `file:${f.name}`;
      loaded.set(key, lr);
      onLoaded(key);
    } catch (err) {
      main.prepend(errorBox(err));
    }
    input.value = '';
  });
  return h('label', { class: 'btn', for: 'file-in' }, 'Open report.json…', input);
}

function unitSelect(value: string | null, onChange: (key: string) => void, label: string): HTMLElement {
  const sel = h('select', { 'aria-label': label },
    h('option', { value: '', disabled: true, selected: !value }, 'Choose a unit…'),
    ...options().map((o) => h('option', { value: o.key, selected: o.key === value }, o.label)));
  sel.addEventListener('change', () => onChange(sel.value));
  return h('label', { class: 'field' }, h('span', {}, label), sel);
}

// ---- viewer --------------------------------------------------------------------------------
function factList(r: Report): string {
  const u = r.unit;
  return [u.floor !== undefined && `floor ${u.floor}`, u.building_kind, u.year_built && `built ${u.year_built}`,
    u.main_orientation && `faces ${u.main_orientation}`, u.has_ac === true ? 'has AC' : u.has_ac === false ? 'no AC' : null]
    .filter(Boolean).join(' · ');
}

function sunControls(r: Report, viewer: Viewer3D | null): HTMLElement {
  const n = r.sun.hours.length;
  let d = 0;
  let hi = defaultHourIndex(r.sun.hours);
  const dateSel = h('select', { id: 'sun-date', 'aria-label': 'Date' },
    ...r.sun.dates.map((date, i) => h('option', { value: String(i) }, date)));
  const slider = h('input', { type: 'range', id: 'sun-hour', min: 0, max: n - 1, step: 1, value: hi, 'aria-label': 'Hour of day (local solar time)' });
  const out = h('output', { for: 'sun-hour', class: 'sun-out', 'aria-live': 'polite' });
  const update = () => {
    const time = formatHour(r.sun.hours[hi]);
    const pos = viewer ? viewer.setSun(d, hi) : r.sun.sun_position[d]?.[hi] ?? null;
    const lit = Object.values(r.sun.patches).filter((p) => p[d]?.[hi]).length;
    slider.setAttribute('aria-valuetext', `${time} solar time`);
    out.textContent = !pos ? time
      : pos[1] <= 0 ? `${time} — sun below the horizon`
        : `${time} — sun az ${pos[0].toFixed(0)}°, el ${pos[1].toFixed(0)}° · sun on the floor in ${lit} room${lit === 1 ? '' : 's'}`;
  };
  dateSel.addEventListener('change', () => { d = sliderToIndex(dateSel.value, r.sun.dates.length); update(); });
  slider.addEventListener('input', () => { hi = sliderToIndex(slider.value, n); update(); });
  update();
  return h('div', { class: 'sun-controls' },
    h('label', { class: 'field' }, h('span', {}, 'Date'), dateSel),
    h('label', { class: 'field grow' }, h('span', {}, 'Time (solar clock)'), slider),
    out,
    h('p', { class: 'muted legend' }, h('span', { class: 'swatch sun' }), 'predicted floor sun patch ',
      h('span', { class: 'swatch win' }), 'window ', h('span', { class: 'swatch ctx' }), 'neighbouring building'));
}

async function renderViewer(): Promise<void> {
  const top = h('div', { class: 'toolbar' });
  const body = h('div', {});
  main.append(top, body);
  let viewer: Viewer3D | null = null;
  cleanup = () => { stopAudio(); viewer?.dispose(); viewer = null; };

  const show = async (key: string) => {
    currentKey = key;
    stopAudio();
    clear(body);
    let lr: LoadedReport;
    try {
      lr = await getReport(key);
    } catch (err) {
      body.append(errorBox(err));
      return;
    }
    if (!key.startsWith('file:')) history.replaceState(null, '', `#/viewer?unit=${encodeURIComponent(key)}`);
    renderTop();
    const r = lr.report;
    banner.textContent = `${STANDING_DISCLAIMER} ${r.disclaimer}`;
    const stage = h('div', { class: 'stage' });
    body.append(
      h('div', { class: 'unit-head' }, h('h2', {}, r.unit.label), badge(r)),
      h('p', { class: 'muted' }, factList(r), r.generated_utc ? ` · generated ${r.generated_utc}` : ''),
      stage);
    viewer?.dispose();
    viewer = null;
    try {
      viewer = new Viewer3D(stage);
      viewer.setReport(r);
    } catch {
      stage.append(h('p', { class: 'panel' }, '3D view unavailable (WebGL not supported). The report cards below still work.'));
    }
    body.append(sunControls(r, viewer), h('h2', {}, 'Room by room'), roomCards(lr));
    if (r.provenance) {
      body.append(h('p', { class: 'muted small' }, 'Provenance: ' + Object.entries(r.provenance).map(([k, v]) => `${k}=${String(v)}`).join(', ')));
    }
  };

  const renderTop = () => {
    clear(top);
    if (index.length || [...loaded.keys()].some((k) => k.startsWith('file:'))) top.append(unitSelect(currentKey, show, 'Unit'));
    top.append(filePicker(show));
  };
  renderTop();

  const wanted = new URLSearchParams(location.hash.split('?')[1] ?? '').get('unit');
  const start = (wanted && index.some((e) => e.id === wanted) && wanted) || (currentKey && options().some((o) => o.key === currentKey) && currentKey) || index[0]?.id;
  if (start) await show(start);
  else body.append(emptyState());
}

// ---- compare -------------------------------------------------------------------------------
async function renderCompare(): Promise<void> {
  cleanup = stopAudio;
  const opts = options();
  if (opts.length < 2) {
    main.append(emptyState(), h('p', { class: 'panel' }, 'Compare needs at least two units (from the index or opened files in the Viewer).'));
    return;
  }
  let a = currentKey && opts.some((o) => o.key === currentKey) ? currentKey : opts[0].key;
  let b = opts.find((o) => o.key !== a)!.key;
  const top = h('div', { class: 'toolbar' });
  const body = h('div', {});
  main.append(top, body);

  const draw = async () => {
    stopAudio();
    clear(top);
    top.append(unitSelect(a, (k) => { a = k; draw(); }, 'Unit A'), unitSelect(b, (k) => { b = k; draw(); }, 'Unit B'));
    clear(body);
    let la: LoadedReport;
    let lb: LoadedReport;
    try {
      [la, lb] = await Promise.all([getReport(a), getReport(b)]);
    } catch (err) {
      body.append(errorBox(err));
      return;
    }
    const rows = summarize(la.report, lb.report, `A (${la.report.unit.label})`, `B (${lb.report.unit.label})`);
    body.append(
      h('section', { class: 'panel summary', 'aria-label': 'Comparison summary' },
        h('h2', {}, 'Is the difference bigger than the uncertainty?'),
        h('ul', {}, ...rows.map((row) => h('li', { class: `verdict ${row.comparison?.verdict ?? 'na'}` },
          h('strong', {}, row.headline.question), ' ', row.text,
          row.a && row.b ? h('span', { class: 'muted' },
            ` Compared: A's ${row.headline.roomRule} (${row.a.room.name ?? row.a.room.kind}) vs B's (${row.b.room.name ?? row.b.room.kind}).`) : null))),
        h('p', { class: 'muted small' }, 'Rule: a unit "wins" only if the two 90 % intervals do not overlap; otherwise it is too close to call. '
          + `Bands below share fixed scales: ${[...new Set(METRICS.map((m) => `${m.min}–${m.max} ${m.unit}`))].join(', ')}.`)),
      h('div', { class: 'compare-grid' },
        ...[['A', la], ['B', lb]].map(([tag, lr]) => {
          const r = (lr as LoadedReport).report;
          return h('section', { class: 'compare-col', 'aria-label': `Unit ${tag}` },
            h('div', { class: 'unit-head' }, h('h2', {}, `${tag}: ${r.unit.label}`), badge(r)),
            h('p', { class: 'muted' }, factList(r)),
            roomCards(lr as LoadedReport));
        })));
  };
  await draw();
}

// ---- router --------------------------------------------------------------------------------
async function route(): Promise<void> {
  cleanup?.();
  cleanup = null;
  clear(main);
  banner.textContent = STANDING_DISCLAIMER;
  const name = (location.hash.match(/^#\/(\w+)/)?.[1] ?? 'viewer') as 'viewer' | 'compare' | 'capture';
  nav.querySelectorAll('a').forEach((a) => a.toggleAttribute('aria-current', a.dataset.route === name));
  if (name === 'capture') cleanup = mountCapture(main);
  else if (name === 'compare') await renderCompare();
  else await renderViewer();
}

async function boot(): Promise<void> {
  try {
    index = await fetchIndex();
  } catch (err) {
    indexError = err instanceof Error ? err.message : String(err);
  }
  window.addEventListener('hashchange', () => { void route(); });
  await route();
  if (import.meta.env.PROD && 'serviceWorker' in navigator) {
    navigator.serviceWorker.register('./sw.js').catch(() => undefined);
  }
}

void boot();
