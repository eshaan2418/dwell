"""Train the Dwell model bundle on the synthetic TRAIN split (until real units exist).

Output: data/synthetic/cache/models_<world>.pkl (git-ignored, regenerated by `make train`).
"""

from __future__ import annotations

import numpy as np

from bench.common import ROOT
from bench.m8_hybrid import NAME, prepare, tables
from bench.synth_dataset import load, load_split
from core.scene import Unit
from hybrid.models import DwellModels, fit_target
from hybrid.priors import HiddenPropertyModel

OUT = ROOT / "data" / "synthetic" / "cache" / f"models_{NAME}.pkl"


def main() -> None:
    np.seterr(all="ignore")
    test_b = set(load_split(NAME)["test_buildings"])
    recs = [r for r in load(NAME) if r["true"]["building_id"] not in test_b]
    hidden = HiddenPropertyModel().fit([(Unit.from_dict(r["true"]), Unit.from_dict(r["obs"])) for r in recs])
    tabs = tables("main")
    bundle = DwellModels(hidden, trained_on=f"synthetic {NAME} train split ({len(recs)} units)")
    for target in ("sun", "noise", "heat"):
        df = prepare(target, tabs[target])
        tr = df[df.split == "train"].reset_index(drop=True)
        bundle.targets[target] = fit_target(target, tr)
        tm = bundle.targets[target]
        print(target, len(tr), "halfwidth row/room", round(tm.halfwidth("row"), 3), round(tm.halfwidth("room"), 3))
    bundle.save(OUT)
    print("saved", OUT)


if __name__ == "__main__":
    main()
