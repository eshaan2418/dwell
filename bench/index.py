"""Regenerate results/INDEX.md from every results/**/*.json (command, data kind, commit, one-line finding).

Findings are formatted from the JSON values themselves, so INDEX.md never contains hand-typed numbers.
"""

from __future__ import annotations

import json

from core.provenance import RESULTS

COMMANDS = {
    "m1/target_derivation.json": "make m1",
    "m3/recon_synthetic.json": "make m3",
    "m4/locate.json": "make m4",
    "m5/sun.json": "make m5-m8",
    "m6/noise.json": "make m5-m8",
    "m7/heat.json": "make m5-m8",
    "m8/comparison.json": "make m5-m8",
    "m8/sobol.json": "make sobol",
    "m8/hidden_properties.json": "make priors",
    "m10/demo_timing.json": "make demo",
    "m11/study_dryrun.json": "python -m study.analysis --dry-run",
    "m12/release.json": "python -m bench.release_dataset",
    "privacy/scan.json": "make privacy-scan",
    "real/validation.json": "make validate",
}


def finding(rel: str, d: dict) -> str:
    try:
        if rel in ("m5/sun.json", "m6/noise.json", "m7/heat.json"):
            h = d["methods"]["hybrid"]["marginal"]
            p = d["methods"]["physics_inferred"]["marginal"]
            return (
                f"hybrid MAE {h['mae']:.2f} (CI {h['mae_ci95'][0]:.2f}–{h['mae_ci95'][1]:.2f}), coverage "
                f"{h['coverage90']:.2f}; physics-inferred MAE {p['mae']:.2f}"
            )
        if rel == "m1/target_derivation.json":
            v = d["validation"]
            return (
                f"sensor-derived sun hours vs truth: {v['daily_sun_hours_abs_err_mean_h']:.2f} h/day; "
                f"open-window heuristic F1 {d['open_window_heuristic_validation']['f1']:.2f}"
            )
        if rel == "m8/hidden_properties.json":
            return (
                f"glazing acc {d['full']['glazing_acc']:.2f} vs default {d['default_materials']['glazing_acc']:.2f}; "
                f"wall acc {d['full']['wall_acc']:.2f}"
            )
        if rel == "m4/locate.json":
            o = d["orientation"]
            return (
                f"orientation median error: compass {o['compass_averaged']['median_abs_deg']:.1f}°, "
                f"footprint snap {o['footprint_snap']['median_abs_deg']:.1f}°"
            )
        if rel == "m3/recon_synthetic.json":
            t = d["table"]["nominal_120s__good__door_scale"]
            return (
                f"nominal scan: room area err {t['room_area_abs_rel_err_median']:.3f}, "
                f"window recall {t['window_recall']:.2f}"
            )
        if rel == "m8/sobol.json":
            return (
                f"hidden-property share of variance: noise {d['noise']['hidden_property_share_mean']:.2f}, "
                f"heat {d['heat']['hidden_property_share_mean']:.2f}"
            )
        if rel == "m10/demo_timing.json":
            return f"max report generation {d['max_seconds']:.0f} s"
        if rel == "privacy/scan.json":
            return "OK" if d["ok"] else f"{len(d['issues'])} issues"
        if rel == "real/validation.json":
            return d.get("status", f"{d.get('n_units')} real units")
        if rel == "m11/study_dryrun.json":
            return "simulated study: effect recovery + power table"
    except Exception as e:  # keep the index robust to schema changes
        return f"(see file; {type(e).__name__})"
    return ""


def main() -> None:
    rows = [
        "# results/INDEX.md (auto-generated by `python -m bench.index`)",
        "",
        "| Result file | Command | Data | Commit | Finding |",
        "|---|---|---|---|---|",
    ]
    for p in sorted(RESULTS.rglob("*.json")):
        rel = str(p.relative_to(RESULTS))
        d = json.loads(p.read_text())
        pv = d.get("provenance", {})
        rows.append(
            f"| `{rel}` | `{COMMANDS.get(rel, '')}` | {pv.get('data_kind', '?')} | "
            f"{str(pv.get('commit', ''))[:8]}{'*' if pv.get('dirty') else ''} | {finding(rel, d)} |"
        )
    rows += [
        "",
        "`*` = produced from a working tree with uncommitted changes (re-run from a clean checkout for archival).",
    ]
    (RESULTS / "INDEX.md").write_text("\n".join(rows) + "\n")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
